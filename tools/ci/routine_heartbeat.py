#!/usr/bin/env python3
"""Routine heartbeat for Take My Package: opens an issue when a routine stops leaving PRs.

Usage: python tools/ci/routine_heartbeat.py [--repo owner/name] [--dry-run]

No model involved. It applies the alarm table of `.claude/rutinas/auditoria.md` section 1.5
(the last PR per branch prefix against a maximum age) and keeps one issue per routine, label
`rutina-caida`, titled "Rutina caída (latido): <name>": opened when the alarm fires, closed when
the routine leaves a PR again. The PC script opens its own "Rutina de PC caída: build|arte" issues (N-973);
the titles differ on purpose so the two never overwrite each other.
`.claude/rutinas/PRESUPUESTO` (regla 1 bis): a routine that the level leaves out is not an alarm.
`.github/workflows/routine-heartbeat.yml` runs it every 6 hours. Only the standard library.
"""
import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LABEL = "rutina-caida"
TITLE = "Rutina caída (latido): "
# name, branch prefix, max hours without a PR, levels (budget) where the routine still runs.
# Same shape as the table of auditoria.md section 1.5; QA has no alarm (no findings = no PR).
RULES = [
    ("Construcción", "nacho/", 24, {"normal", "ahorro", "minimo"}),
    ("Desarrollador", "exp/D-", 24, {"normal", "ahorro"}),
    ("Build de la PC", "rutina/pc-", 36, {"normal", "ahorro", "minimo"}),
    ("Sesión de arte", "arte/", 48, {"normal", "ahorro"}),
    ("Revisión", "rutina/revision-", 8 * 24, {"normal", "ahorro"}),
    ("Mantenimiento", "rutina/mant-", 8 * 24, {"normal", "ahorro"}),
    ("Lanzamiento", "rutina/lanzamiento-", 32 * 24, {"normal", "ahorro"}),
]
# PRs read per rule. Each rule asks GitHub for its own prefix (`head:` matches by prefix), so a
# monthly routine stays visible however many developer PRs came after it: one `--limit 200` list of
# every PR only reached back 16 days on 2026-10-21 and Lanzamiento alarmed at 20 days of 32 (N-974.4).
PER_RULE = 20


def budget_level(text):
    """First word of PRESUPUESTO; no file means normal."""
    words = (text or "").split()
    word = re.sub(r"[^a-z]", "", words[0].lower()) if words else ""
    return word if word in ("ahorro", "minimo") else "normal"


def evaluate(prs, now, level):
    """Alarms as {name: message}; `prs` is `gh pr list --json headRefName,createdAt`."""
    alarms = {}
    for name, prefix, max_hours, levels in RULES:
        if level not in levels:
            continue
        times = [dt.datetime.fromisoformat(p["createdAt"].replace("Z", "+00:00"))
                 for p in prs if p["headRefName"].startswith(prefix)]
        if not times:
            alarms[name] = f"ningún PR de una rama `{prefix}*` (máximo {max_hours} h)"
            continue
        age = (now - max(times)).total_seconds() / 3600
        if age > max_hours:
            alarms[name] = f"último PR `{prefix}*` hace {age:.0f} h (máximo {max_hours} h)"
    return alarms


def fetch_prs(repo):
    """The newest PRs of every rule's prefix, newest first per rule (see PER_RULE)."""
    prs = []
    for _name, prefix, _hours, _levels in RULES:
        prs += json.loads(gh("pr", "list", *repo, "--state", "all", "--search", f"head:{prefix} sort:created-desc",
                             "--limit", str(PER_RULE), "--json", "headRefName,createdAt"))
    return prs


def gh(*args):
    proc = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        sys.exit(f"gh {' '.join(args)}: {proc.stderr.strip()}")
    return proc.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default="")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    repo = ["--repo", args.repo] if args.repo else []

    path = ROOT / ".claude/rutinas/PRESUPUESTO"
    level = budget_level(path.read_text(encoding="utf-8") if path.exists() else "")
    alarms = evaluate(fetch_prs(repo), dt.datetime.now(dt.timezone.utc), level)
    issues = json.loads(gh("issue", "list", *repo, "--label", LABEL, "--state", "open",
                           "--limit", "100", "--json", "number,title"))
    open_by_title = {i["title"]: i["number"] for i in issues if i["title"].startswith(TITLE)}
    print(f"presupuesto: {level}; alarmas: {sorted(alarms) or 'ninguna'}")

    for name, why in alarms.items():
        title = TITLE + name
        if title in open_by_title:
            continue
        body = (f"El latido de las rutinas (`routine-heartbeat.yml`, cada 6 h) no ve rastro de **{name}**: "
                f"{why}.\n\nSuele arreglarse fuera del repo (la PC apagada, un trigger deshabilitado, el "
                f"cupo del plan; regla 13). Se cierra solo cuando la rutina vuelve a abrir un PR.\n"
                f"Presupuesto actual: `{level}`.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_")
        print("abre:", title)
        if not args.dry_run:
            gh("label", "create", LABEL, *repo, "--color", "B60205",
               "--description", "Una rutina dejó de producir", "--force")
            gh("issue", "create", *repo, "--title", title, "--label", LABEL, "--body", body)
    for title, number in open_by_title.items():
        if title[len(TITLE):] not in alarms:
            print("cierra:", title)
            if not args.dry_run:
                gh("issue", "close", str(number), *repo, "--comment",
                   "La rutina volvió a dejar rastro: cierro el aviso.")


if __name__ == "__main__":
    main()
